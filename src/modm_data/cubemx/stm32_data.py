ignored_devices = [
    "STM32WL5M",
    "STM32WB1M",
    "STM32WB5M",
    "STM32WBA",
]


def ignoreDevice(device_id: str) -> bool:
    for ignore in ignored_devices:
        if device_id.startswith(ignore):
            return True
    return False


